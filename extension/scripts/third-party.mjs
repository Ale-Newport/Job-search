// Writes (or checks) extension/tests/widgets/THIRD_PARTY.md: the third-party code that the committed widget fixtures bundle
// (extension/tests/widgets/fixtures/*.js and chunks/), listed from tests/widgets/package.json, package-lock.json and the imports
// of tests/widgets/src/*.jsx. Nothing here is shipped in the extension or the app: the fixtures are test pages. They are committed
// as minified bundles WITHOUT their licence banners (esbuild legalComments: "none"), so this file is where the notice lives.
//
//   node scripts/third-party.mjs            write the file
//   node scripts/third-party.mjs --check    exit 1 (and say why) when the committed file does not match the lock file
//
// Deterministic: sorted, no dates. The unit test tests/unit/third-party.test.mjs runs --check, so a changed lock file fails the
// tests until the file is regenerated.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const widgets = join(root, "tests", "widgets");
const output = join(widgets, "THIRD_PARTY.md");

const json = (path) => JSON.parse(readFileSync(path, "utf8"));
const pkg = json(join(widgets, "package.json"));
const lock = json(join(widgets, "package-lock.json"));

/** `node_modules/@scope/name` or `node_modules/a/node_modules/b` -> the package's own name. */
const nameOf = (key) => key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
const packages = Object.entries(lock.packages ?? {})
  .filter(([key]) => key !== "")
  .map(([key, entry]) => ({ name: nameOf(key), version: entry.version, license: entry.license ?? "not stated in the lock file", dev: entry.dev === true }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));
const direct = Object.keys({ ...pkg.dependencies, ...pkg.devDependencies }).sort();
const byName = new Map(packages.map((entry) => [entry.name, entry]));

/** Bare module specifiers a demo imports, reduced to the npm package name. */
function importedPackages(source) {
  const found = new Set();
  for (const match of source.matchAll(/(?:from\s+|import\s+|import\()\s*["']([^"'.][^"']*)["']/g)) {
    const parts = match[1].split("/");
    found.add(match[1].startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]);
  }
  return [...found].sort();
}
const demos = readdirSync(join(widgets, "src"))
  .filter((name) => name.endsWith(".jsx") && !name.startsWith("_"))
  .sort()
  .map((name) => ({ demo: name.replace(/\.jsx$/, ""), imports: importedPackages(readFileSync(join(widgets, "src", name), "utf8")) }));

const licenseCount = new Map();
for (const entry of packages) licenseCount.set(entry.license, (licenseCount.get(entry.license) ?? 0) + 1);

const row = (...cells) => `| ${cells.join(" | ")} |`;
const link = (entry) => `[${entry.name}](https://www.npmjs.com/package/${entry.name}/v/${entry.version})`;
const lines = [
  "# Third-party code in the widget test fixtures",
  "",
  "<!-- Generated by extension/scripts/third-party.mjs from tests/widgets/package.json and package-lock.json. Do not edit by hand:",
  "     run `node extension/scripts/third-party.mjs` after changing the lock file (the unit tests fail until you do). -->",
  "",
  "`extension/tests/widgets/fixtures/` holds demo pages built from real open-source libraries (see `README.md` in this folder) and",
  "bundled into minified ES modules by `build-fixtures.mjs`. The bundles keep no licence banners, so this file lists the libraries they",
  "are built from and everything those depend on (a superset of what ends up in the bundles), at the pinned versions of",
  "`package-lock.json`, with each package's licence. **These files are test fixtures only: they are not part",
  "of the Meridian Assistant extension (`extension/dist`) or of the Meridian app.** `build.mjs` does not copy anything from `tests/`,",
  "and the sidecar embeds only `extension/dist/chrome`.",
  "",
  "Every package below is under a permissive licence (counts at the end). Each licence requires its copyright notice and permission",
  "notice to accompany copies of the software: the full text, with the copyright holders, is in the `LICENSE` file of each package.",
  "Run `npm ci` in this folder and read `node_modules/<package>/LICENSE*`, or open the npm page linked in the tables.",
  "",
  "## Libraries the demo pages use directly",
  "",
  row("Package", "Pinned version", "Licence"),
  row("---", "---", "---"),
  ...direct.map((name) => {
    const entry = byName.get(name);
    return entry ? row(link(entry), entry.version, entry.license) : row(name, "missing from the lock file", "?");
  }),
  "",
  "## Which demo bundles which library",
  "",
  row("Fixture bundle", "Imports"),
  row("---", "---"),
  ...demos.map(({ demo, imports }) => row(`\`fixtures/${demo}.js\``, imports.map((name) => `\`${name}\``).join(", ") || "none")),
  "",
  "The bundles also contain whatever those libraries import in turn (the next section). Shared code is split into `fixtures/chunks/`.",
  "",
  "## Everything in the lock file (the libraries above and their dependencies)",
  "",
  row("Package", "Version", "Licence"),
  row("---", "---", "---"),
  ...packages.map((entry) => row(link(entry), entry.version, entry.license)),
  "",
  "## Licences in use",
  "",
  row("Licence", "Packages"),
  row("---", "---"),
  ...[...licenseCount].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([license, count]) => row(license, String(count))),
  "",
  "## Vendored copy: React for the controlled-input fixture",
  "",
  "`extension/tests/fixtures/vendor/` holds the unmodified production builds of React and ReactDOM (MIT). Its own notice is",
  "`LICENSE-react.txt` next to the files, and `README.txt` there says what they are for. They are not shipped either.",
  "",
];
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(output) ? readFileSync(output, "utf8") : "";
  if (current !== text) {
    console.error(`${relative(root, output)} is out of date with tests/widgets/package-lock.json: run node scripts/third-party.mjs`);
    process.exit(1);
  }
  console.log(JSON.stringify({ ok: true, file: relative(root, output), packages: packages.length }));
} else {
  writeFileSync(output, text);
  console.log(JSON.stringify({ wrote: relative(root, output), packages: packages.length, direct: direct.length }));
}
