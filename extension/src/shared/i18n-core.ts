// Runtime dictionary for the options page and the worker (English + Spanish). The manifest strings live in _locales/;
// the in-page assistant UI has its own dictionary in content/i18n.ts. The user can pick a language that differs from
// the browser's, which chrome.i18n cannot do, hence this small runtime table.

import type { Language } from "./protocol";
import type { StoredPrefs } from "./messages";

export type Lang = "en" | "es";

/** `auto` follows the browser's UI language; anything that is not Spanish falls back to English. */
export function resolveLanguage(preference: Language | string | null | undefined, uiLanguage: string | null | undefined): Lang {
  const choice = preference === "en" || preference === "es" ? preference : "auto";
  if (choice !== "auto") return choice;
  const ui = String(uiLanguage ?? "").toLowerCase();
  return ui === "es" || ui.startsWith("es-") || ui.startsWith("es_") ? "es" : "en";
}

/** The app's last-known setting wins when it is explicit, then the extension's own choice, then the browser. */
export function languageFromPrefs(prefs: StoredPrefs, uiLanguage: string | null | undefined): Lang {
  const fromApp = prefs.settings?.language;
  return resolveLanguage(fromApp && fromApp !== "auto" ? fromApp : prefs.language, uiLanguage);
}

