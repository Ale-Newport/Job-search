export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, es };

export function t(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  const template = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

/** Current language for worker-produced strings (toolbar tooltip): prefs first, browser UI language otherwise. */
export function browserLanguage(): string {
  try {
    return chrome.i18n.getUILanguage();
  } catch {
    return typeof navigator !== "undefined" ? navigator.language : "en";
  }
}
