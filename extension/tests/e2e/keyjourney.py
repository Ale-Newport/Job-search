"""Keyboard-only journeys: a whole application completed with Tab, Shift+Tab, Enter and Esc and nothing else.

Two things make these journeys honest:

* ``Keys`` is the ONLY way a journey touches the page after the toolbar activation. It refuses any key outside
  Tab / Shift+Tab / Enter / Esc, and ``watch_pointer`` / ``pointer_events`` prove afterwards that no trusted mouse event ever reached any frame.
* the end state is compared with a JSON file (``extension/tests/fixtures/journeys/<name>.expected.json``) that lists the value
  of EVERY control of the form, filled or not: what the assistant may fill is filled, everything else (consent, demographics,
  unknown answers, files that are not the CV, the CAPTCHA response) is provably still empty.
"""

from __future__ import annotations

import json
from pathlib import Path

from playwright.async_api import Frame, Page

import ui
from framework import check

EXPECTED_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "journeys"
ALLOWED = {"Tab", "Shift+Tab", "Enter", "Escape"}


class Keys:
    """The keyboard of a journey. Every press goes through here, so the log is the journey."""

    def __init__(self, page: Page) -> None:
        self.page = page
        self.log: list[str] = []

    async def press(self, key: str) -> None:
        assert key in ALLOWED, f"a keyboard-only journey may not press {key!r}"
        self.log.append(key)
        await self.page.keyboard.press(key)

    async def tab(self) -> None:
        await self.press("Tab")

    async def shift_tab(self) -> None:
        await self.press("Shift+Tab")

    async def enter(self) -> None:
        await self.press("Enter")

    async def esc(self) -> None:
        await self.press("Escape")


POINTER_JS = """() => { if (window.__pointerWatch) return; window.__pointerWatch = [];
  for (const type of ['pointerdown', 'mousedown', 'mouseup', 'click']) {
    addEventListener(type, (e) => { if (e.isTrusted && !(type === 'click' && e.detail === 0)) window.__pointerWatch.push(type); }, true);
  } }"""


async def watch_pointer(page: Page) -> None:
    """From now on record every trusted mouse event in every frame (a click generated by Enter has detail 0 and is not one)."""
    for frame in page.frames:
        try:
            await frame.evaluate(POINTER_JS)
        except Exception:  # noqa: BLE001 - about:blank
            continue


async def pointer_events(page: Page) -> list[str]:
    found: list[str] = []
    for frame in page.frames:
        try:
            found.extend(await frame.evaluate("window.__pointerWatch || []"))
        except Exception:  # noqa: BLE001
            continue
    return found


SNAPSHOT_JS = """() => {
  const out = {};
  const name = (el) => el.id || el.name;
  for (const el of document.querySelectorAll('input, select, textarea, [contenteditable=true]')) {
    const type = el.type || '';
    if (['hidden', 'password', 'submit', 'button', 'reset', 'image'].includes(type) || !name(el)) continue;
    if (type === 'radio') { if (!(el.name in out)) out[el.name] = null; if (el.checked) out[el.name] = el.value; }
    else if (type === 'checkbox') out[el.id || el.name] = el.checked;
    else if (type === 'file') out[name(el)] = [...el.files].map((f) => f.name).join(',');
    else if (el.tagName === 'SELECT') out[name(el)] = el.multiple ? [...el.selectedOptions].map((o) => o.label) : (el.selectedOptions[0] ? el.selectedOptions[0].label : '');
    else if (el.isContentEditable) out[name(el)] = el.innerText;
    else out[name(el)] = el.value;
  }
  for (const el of document.querySelectorAll('[aria-pressed]')) out[el.id || el.textContent.trim()] = el.getAttribute('aria-pressed');
  return out;
}"""


async def snapshot(page: Page) -> dict[str, dict]:
    """Every control of every frame: {'top': {...}, 'frame:<file>': {...}}."""
    result: dict[str, dict] = {}
    for frame in page.frames:
        try:
            values = await frame.evaluate(SNAPSHOT_JS)
        except Exception:  # noqa: BLE001
            continue
        if not values:
            continue
        key = "top" if frame == page.main_frame else "frame:" + frame.url.rsplit("/", 1)[-1].split("?")[0]
        result[key] = values
    return result


def load_expected(name: str) -> dict:
    return json.loads((EXPECTED_DIR / f"{name}.expected.json").read_text())


def matches(actual: object, expected: object) -> bool:
    """Exact equality, except for ``{"$contains": text}`` (an AI draft: it must contain that sentence and be non-trivial)."""
    if isinstance(expected, dict) and set(expected) == {"$contains"}:
        return isinstance(actual, str) and expected["$contains"] in actual
    return actual == expected


def differences(actual: dict[str, dict], expected: dict[str, dict]) -> list[str]:
    problems: list[str] = []
    for frame in sorted(set(actual) | set(expected)):
        have, want = actual.get(frame), expected.get(frame)
        if want is None or have is None:
            problems.append(f"{frame}: {'unexpected frame' if want is None else 'frame missing'}")
            continue
        for control in sorted(set(have) | set(want)):
            if control not in want:
                problems.append(f"{frame}/{control}: not in the expected file (value {have[control]!r})")
            elif control not in have:
                problems.append(f"{frame}/{control}: missing from the page")
            elif not matches(have[control], want[control]):
                problems.append(f"{frame}/{control}: {have[control]!r} != expected {want[control]!r}")
    return problems


async def assert_form_state(page: Page, name: str) -> None:
    """The final form state equals the expected JSON, control by control."""
    problems = differences(await snapshot(page), load_expected(name))
    check(f"{name}: the final form state equals {name}.expected.json (every control of every frame)", not problems, problems[:8])


async def native_tab_until(page: Page, keys: Keys, selector: str, *, limit: int = 8) -> int:
    """A keyboard user starts at the top of the page: Tab (the browser's own, the assistant steps aside off a field) until
    the first assist field has focus. Nothing may be inserted on the way. Returns how many presses it took."""
    for count in range(1, limit + 1):
        await keys.tab()
        if await page.evaluate("(sel) => document.activeElement === document.querySelector(sel)", selector):
            return count
    raise AssertionError(f"{selector} did not get focus within {limit} Tab presses (focus is on {await ui.focused_id(page)!r})")


async def frame_active_id(frame: Frame) -> str:
    return await frame.evaluate("(document.activeElement && (document.activeElement.id || document.activeElement.tagName)) || ''")
